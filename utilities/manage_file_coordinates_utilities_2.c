#include "../fdf.h"

int	ishex(char *str)
{
	size_t	i;

	if (str[0] == '0' && (str[1] == 'x' || str[1] == 'X'))
	{
		i = 2;
		while (str[i] && i < 8 && ((str[i] >= '0' && str[i] <= '9')
			|| (str[i] >= 'A' && str[i] <= 'F')
			|| (str[i] >= 'a' && str[i] <= 'f')))
			i++;
		if (!str[i])
			return (1);
	}
	return (0);
}
